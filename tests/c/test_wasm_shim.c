/* The browser engine's C, compiled and run natively.
 *
 * web/cognator_wasm.c is otherwise built by exactly one thing -- emcc, in
 * web/build-wasm.sh -- and run by exactly one thing, a browser. That left it
 * with no sanitizer coverage and no assertions of any kind, which is how a
 * stack overflow in the WebAssembly build reached a published page: the
 * numbers were right, the page rendered, and the JSON came back malformed.
 *
 * This does not test Emscripten. It tests the shim's own logic -- that it
 * builds a document that parses, that the fields carry the values the engine
 * computed, that a bad input is an error object rather than a crash -- under
 * whatever sanitizer the surrounding build was configured with.
 */

#include <assert.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

char *cognator_detect_json(const char *csv, const char *options_json);
void cognator_free(char *ptr);
const char *cognator_system(void);

/* Enough of a JSON reader to assert on a field. A parser would be a
 * dependency, and the shim's output is generated by code in the file next
 * door: what has to be checked is that a key is followed by a value at all,
 * which is exactly what the stack overflow broke. */
static const char *field(const char *json, const char *key) {
    static char needle[64];
    const char *at;

    snprintf(needle, sizeof(needle), "\"%s\":", key);
    at = strstr(json, needle);
    return at == NULL ? NULL : at + strlen(needle);
}

static void assert_field_nonempty(const char *json, const char *key) {
    const char *value = field(json, key);

    if (value == NULL) {
        fprintf(stderr, "missing key %s in: %s\n", key, json);
        abort();
    }
    /* The overflow left `"rows":` followed directly by the next separator. */
    if (*value == ',' || *value == '}' || *value == ']') {
        fprintf(stderr, "empty value for %s in: %s\n", key, json);
        abort();
    }
}

int main(void) {
    const char *csv =
        "ID,Language_ID,Concept,Segments,Family,Cognacy\n"
        "f1,Latin,NIGHT,n o k t e,romance,night_1\n"
        "f2,Italian,NIGHT,n o t t e,romance,night_1\n"
        "f3,Spanish,NIGHT,n o t e,romance,night_1\n"
        "f4,Latin,EIGHT,o k t o,romance,eight_1\n"
        "f5,Italian,EIGHT,o t t o,romance,eight_1\n"
        "f6,Spanish,EIGHT,o t o,romance,eight_1\n";
    char *out;
    const char *system_name;

    system_name = cognator_system();
    assert(system_name != NULL);
    assert(system_name[0] != '\0');

    out = cognator_detect_json(csv, "{\"preset\":\"support-adaptive-bridge\"}");
    assert(out != NULL);
    assert(strstr(out, "\"ok\":true") != NULL);

    /* Every numeric field the shim formats by hand. These are the ones that
     * came back empty when the stack was too small, and an empty one makes the
     * whole document unparseable in the browser. */
    assert_field_nonempty(out, "rows");
    assert_field_nonempty(out, "precision");
    assert_field_nonempty(out, "recall");
    assert_field_nonempty(out, "f1");
    assert_field_nonempty(out, "confidence");
    assert_field_nonempty(out, "cluster_size");

    /* A cluster id is family:concept:index, and the index is the part that
     * disappeared. Asserting on the whole string is what catches a truncation
     * anywhere in it. */
    assert(strstr(out, "\"pred\":\"romance:NIGHT:0\"") != NULL);
    assert(strstr(out, "\"pred\":\"romance:EIGHT:0\"") != NULL);

    /* Six input rows, six predictions. */
    assert(strstr(out, "\"rows\":6") != NULL);
    {
        const char *p = out;
        int seen = 0;
        while ((p = strstr(p, "\"eval_id\":")) != NULL) {
            seen++;
            p += 1;
        }
        assert(seen == 6);
    }
    cognator_free(out);

    /* Input the reader refuses is an error object, not a crash and not a
     * truthy result. */
    out = cognator_detect_json("not,a,wordlist\n1,2,3\n", "{}");
    assert(out != NULL);
    assert(strstr(out, "\"ok\":true") == NULL);
    cognator_free(out);

    /* Empty input, and options that are not JSON at all. */
    out = cognator_detect_json("", "{}");
    assert(out != NULL);
    cognator_free(out);

    out = cognator_detect_json(csv, "this is not json");
    assert(out != NULL);
    cognator_free(out);

    cognator_free(NULL);
    return 0;
}
